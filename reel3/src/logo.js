// Monogram in 3D: the exact bars as extruded solids, the app-icon tile, and
// the "packed" layout — the same icon rebuilt from horizontal strips of pills.
import * as THREE from 'three';
import { LOGO, inGlyph, inTile, C } from './brand.js';
import { rng } from './util.js';

export const LOGO_SIZE = 7;            // world units for the 100-unit tile
export const LOGO_K = LOGO_SIZE / 100;
export const LOGO_LIFT = 0.35;          // tile floats this far above the floor
export const TILE_DEPTH = 0.7;
export const GLYPH_DEPTH = 0.32;
export const GLYPH_Z = TILE_DEPTH / 2 + GLYPH_DEPTH / 2 - 0.02;

// svg (x, y-down) → logo-local (x right, y up), tile centred on x, sitting above floor
export const L = (x, y) => [(x - 50) * LOGO_K, (100 - y) * LOGO_K + LOGO_LIFT];

function barShape(b) {
  const [x0, y0, x1, y1] = b.rect, r = LOGO.r;
  const s = new THREE.Shape();
  const P = (x, y) => L(x, y);
  // build the outline in svg space, then map; arcs are generated by hand so the mapping stays exact
  const pts = [];
  const arc = (cx, cy, a0, a1) => { for (let i = 0; i <= 16; i++) { const a = a0 + (a1 - a0) * (i / 16); pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]); } };
  if (b.dir === 'up') { pts.push([x0, y1]); arc(b.cap[0], b.cap[1], Math.PI, Math.PI * 2); pts.push([x1, y1]); }
  if (b.dir === 'left') { pts.push([x1, y0]); pts.push([x1, y1]); arc(b.cap[0], b.cap[1], Math.PI / 2, Math.PI * 1.5); }
  if (b.dir === 'right') { pts.push([x0, y0]); arc(b.cap[0], b.cap[1], -Math.PI / 2, Math.PI / 2); pts.push([x0, y1]); }
  pts.forEach(([x, y], i) => { const [u, v] = P(x, y); i ? s.lineTo(u, v) : s.moveTo(u, v); });
  s.closePath();
  return s;
}

function tileShape() {
  const s = new THREE.Shape(), r = LOGO.tileR;
  const pts = [];
  const corner = (cx, cy, a0) => { for (let i = 0; i <= 12; i++) { const a = a0 + (Math.PI / 2) * (i / 12); pts.push([cx + r * Math.cos(a), cy + r * Math.sin(a)]); } };
  corner(100 - r, r, -Math.PI / 2); corner(100 - r, 100 - r, 0); corner(r, 100 - r, Math.PI / 2); corner(r, r, Math.PI);
  pts.forEach(([x, y], i) => { const [u, v] = L(x, y); i ? s.lineTo(u, v) : s.moveTo(u, v); });
  s.closePath();
  return s;
}

export function makeLogo() {
  const group = new THREE.Group();
  const tileMat = new THREE.MeshPhysicalMaterial({ color: C.ink, roughness: 0.5, clearcoat: 1.0, clearcoatRoughness: 0.12, envMapIntensity: 0.45 });
  const glyphMat = new THREE.MeshPhysicalMaterial({ color: C.paper, roughness: 0.5, clearcoat: 0.35, clearcoatRoughness: 0.3, emissive: new THREE.Color(C.paper), emissiveIntensity: 0.42 });
  const bevel = { bevelEnabled: true, bevelThickness: 0.06, bevelSize: 0.05, bevelSegments: 3, curveSegments: 1 };
  const tileGeo = new THREE.ExtrudeGeometry(tileShape(), { depth: TILE_DEPTH - 0.12, ...bevel });
  tileGeo.translate(0, 0, -(TILE_DEPTH - 0.12) / 2);
  const tile = new THREE.Mesh(tileGeo, tileMat);
  tile.castShadow = tile.receiveShadow = true;
  group.add(tile);
  const bars = LOGO.bars.map(b => {
    const extra = b.id === 'A' ? 0.03 : 0;
    const g = new THREE.ExtrudeGeometry(barShape(b), { depth: GLYPH_DEPTH - 0.1 + extra, ...bevel, bevelThickness: 0.05, bevelSize: 0.04 });
    g.translate(0, 0, -(GLYPH_DEPTH - 0.1 - extra) / 2);
    // pivot each bar on its own centre so it can fly in and spin
    const [x0, y0, x1, y1] = b.rect;
    const cx = (Math.min(x0, b.cap[0] - (b.dir === 'left' ? LOGO.r : 0)) + Math.max(x1, b.cap[0] + (b.dir === 'right' ? LOGO.r : 0))) / 2;
    const cy = (Math.min(y0, b.cap[1] - (b.dir === 'up' ? LOGO.r : 0)) + y1) / 2;
    const [u, v] = L(cx, cy);
    g.translate(-u, -v, 0);
    const m = new THREE.Mesh(g, glyphMat.clone());
    m.castShadow = m.receiveShadow = true;
    m.userData.home = new THREE.Vector3(u, v, GLYPH_Z);
    m.position.copy(m.userData.home);
    group.add(m);
    return m;
  });
  return { group, tile, bars, tileMat, glyphMat };
}

// Packed layout: rows of pills, aligned so bar edges fall on row boundaries.
export function packLayout(seed = 7) {
  const R = rng(seed);
  const rowH = 2.875, y0 = 0.5, gap = 0.55;
  const out = [];
  for (let row = 0; y0 + row * rowH < 100; row++) {
    const yc = y0 + (row + 0.5) * rowH;
    if (yc > 99.5) break;
    // scan the row at 0.25-unit resolution and split into runs of constant material
    const runs = [];
    let cur = null;
    for (let x = 0; x <= 100.001; x += 0.25) {
      const m = !inTile(x, yc) ? null : inGlyph(x, yc) ? 'glyph' : 'tile';
      if (!cur || cur.m !== m) { if (cur && cur.m) runs.push(cur); cur = { m, x0: x, x1: x }; } else cur.x1 = x;
    }
    if (cur && cur.m) runs.push(cur);
    for (const run of runs) {
      const L0 = run.x1 - run.x0;
      // chop each run into pills of 3–11 units
      let x = run.x0;
      const pieces = [];
      while (run.x1 - x > 0.01) {
        let len = run.m === 'glyph' ? R.range(4, 9) : R.range(4, 12);
        if (run.x1 - x - len < 3) len = run.x1 - x;
        pieces.push([x, Math.min(run.x1, x + len)]);
        x += len;
      }
      for (const [a, b] of pieces) {
        const len = b - a - gap, h = rowH - gap;
        if (len < h * 0.9) continue;
        out.push({ m: run.m, x: (a + b) / 2, y: yc, len: Math.max(len, h), h, run: L0 });
      }
    }
  }
  return out;
}
